export type UiTextKey = keyof typeof text

const interpolate = (template: string, values?: Record<string, string | number>) =>
  template.replace(/\{(\w+)\}/g, (_, key: string) => String(values?.[key] ?? `{${key}}`))

export const translateUi = (language: string, key: UiTextKey, values?: Record<string, string | number>) => {
  const entry = text[key]
  const template = language === 'zh' ? entry.zh : entry.en
  return interpolate(template, values)
}

export const useUiText = () => {
  const { language } = useAuthStore()

  return useCallback(
    (key: UiTextKey, values?: Record<string, string | number>) => translateUi(language, key, values),
    [language],
  )
}
