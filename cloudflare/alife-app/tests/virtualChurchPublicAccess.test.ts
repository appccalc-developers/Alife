test('production requires both explicit public access and V3 as the released visual', () => {
  assert.equal(allowsVirtualChurchGuestVisit({ DEV: false }), false)
  assert.equal(allowsVirtualChurchGuestVisit({ DEV: false, VITE_VIRTUAL_CHURCH_PUBLIC_ACCESS: 'enabled' }), false)
  assert.equal(allowsVirtualChurchGuestVisit({ DEV: false, VITE_VIRTUAL_CHURCH_VISUAL_DEFAULT: 'v3' }), false)
  assert.equal(allowsVirtualChurchGuestVisit({ DEV: false, VITE_VIRTUAL_CHURCH_PUBLIC_ACCESS: 'true', VITE_VIRTUAL_CHURCH_VISUAL_DEFAULT: 'v3' }), false)
  assert.equal(allowsVirtualChurchGuestVisit({ DEV: false, VITE_VIRTUAL_CHURCH_PUBLIC_ACCESS: 'enabled', VITE_VIRTUAL_CHURCH_VISUAL_DEFAULT: 'v2' }), false)
  assert.equal(allowsVirtualChurchGuestVisit({ DEV: false, VITE_VIRTUAL_CHURCH_PUBLIC_ACCESS: 'enabled', VITE_VIRTUAL_CHURCH_VISUAL_DEFAULT: 'v3' }), true)
})

test('production workflow wires both opt-in flags to the build and checks public route policy first', () => {
  const workflow = readFileSync(new URL('../../../.github/workflows/deploy-cloudflare-worker.yml', import.meta.url), 'utf8').replace(/\r\n/g, '\n')
  const build = workflow.split('      - name: Build Frontend\n')[1]?.split('\n      - name:')[0]
  assert.ok(build, 'the production frontend build step must exist')
  assert.equal(build.match(/^          VITE_VIRTUAL_CHURCH_PUBLIC_ACCESS: (.+)$/m)?.[1], "${{ vars.VITE_VIRTUAL_CHURCH_PUBLIC_ACCESS || 'disabled' }}")
  assert.equal(build.match(/^          VITE_VIRTUAL_CHURCH_VISUAL_DEFAULT: (.+)$/m)?.[1], "${{ vars.VITE_VIRTUAL_CHURCH_VISUAL_DEFAULT || 'v2' }}")
  assert.match(build, /\n        run: npm run build(?:\n|$)/)
  const policyCheck = workflow.indexOf('        run: node --test --experimental-strip-types tests/virtualChurchPublicAccess.test.ts')
  assert.ok(policyCheck >= 0 && policyCheck < workflow.indexOf('      - name: Build Frontend\n'))
  assert.equal(allowsVirtualChurchGuestVisit({ DEV: false, VITE_VIRTUAL_CHURCH_PUBLIC_ACCESS: 'disabled', VITE_VIRTUAL_CHURCH_VISUAL_DEFAULT: 'v2' }), false)
  assert.equal(allowsVirtualChurchGuestVisit({ DEV: false, VITE_VIRTUAL_CHURCH_PUBLIC_ACCESS: 'disabled', VITE_VIRTUAL_CHURCH_VISUAL_DEFAULT: 'v3' }), false)
})

