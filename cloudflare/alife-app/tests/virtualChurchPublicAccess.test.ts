test('a newly public scene resumes an old onboarding return target with query and hash intact', () => {
  for (const path of ['/virtual-church', '/virtual-church/study-room', '/virtual-church/main-hall']) {
    const target = `${path}?profile3d=mobile#entrance`
    const search = `?returnTo=${encodeURIComponent(target)}`
    assert.equal(resolveVirtualChurchGuestReturn(search, true), target)
    assert.equal(resolveVirtualChurchGuestReturn(search, false), '')
  }
})

test('scene recovery cannot consume an identity intent or expand the public route whitelist', () => {
  for (const intent of ['activation', 'groupJoin', 'application', '', 'unknown']) {
    assert.equal(resolveVirtualChurchGuestReturn(`?intent=${intent}&returnTo=%2Fvirtual-church`, true), '')
  }
  for (const target of [
    '/groups/private', '/church/manage', '/admin', '/study?from=virtual-church-study-room',
    '/virtual-church/private', '/virtual-church/../admin', '/virtual-church//',
    'https://other.example/virtual-church', '//other.example/virtual-church',
    '/virtual-church\\escape', '/onboarding?returnTo=/virtual-church',
    '/internal/alpha-login', `/virtual-church?${String.fromCharCode(10)}escape`,
    '/%2fvirtual-church', '',
  ]) {
    assert.equal(resolveVirtualChurchGuestReturn(`?returnTo=${encodeURIComponent(target)}`, true), '', target)
  }
  assert.equal(resolveVirtualChurchGuestReturn('', true), '')
})

test('recovery accepts only the exact returnTo-only shape generated by the old member guard', () => {
  for (const key of ['application', 'line_login', 'line_error', 'source', 'futureWorkflow']) {
    assert.equal(resolveVirtualChurchGuestReturn(`?${key}=test&returnTo=%2Fvirtual-church`, true), '')
  }
  assert.equal(resolveVirtualChurchGuestReturn('?returnTo=%2Fvirtual-church&returnTo=%2Fadmin', true), '')
  assert.equal(resolveVirtualChurchGuestReturn('?returnTo=%2Fvirtual-church&returnTo=%2Fvirtual-church', true), '')
})

test('only onboarding recovery skips bootstrap and navigation happens before auth readiness', () => {
  const bootstrap = readFileSync(new URL('../src/app/components/AuthBootstrapGate.tsx', import.meta.url), 'utf8')
  assert.match(bootstrap, /location.pathname === '\/onboarding' && Boolean\(resolveVirtualChurchGuestReturn\(location.search, guestVisitEnabled\)\)/)
  const routes = readFileSync(new URL('../src/app/routing/AppRoutes.tsx', import.meta.url), 'utf8')
  const onboarding = routes.split('const OnboardingRoute =')[1].split('const MemberRoute =')[0]
  assert.match(onboarding, /if \(guestReturn\) return <Navigate to=\{guestReturn\} replace \/>/)
  assert.ok(onboarding.indexOf('if (guestReturn)') < onboarding.indexOf('if (!auth.initialized)'))
  const member = routes.split('const MemberRoute =')[1].split('const VirtualChurchPreviewRoute =')[0]
  assert.match(member, /!auth.loading && !auth.isGuest/)
  assert.doesNotMatch(member, /guestReturn|resolveVirtualChurchGuestReturn/)
  const shell = readFileSync(new URL('../src/app/AppShell.tsx', import.meta.url), 'utf8')
  assert.match(shell, /const publicSceneReturn = location.pathname === '\/onboarding' && Boolean\(resolveVirtualChurchGuestReturn\(location.search, guestVisitEnabled\)\)/)
  assert.match(shell, /const showSceneShell = usesVirtualChurchSceneShell\(location, guestVisitEnabled\) \|\| publicSceneReturn/)
})

