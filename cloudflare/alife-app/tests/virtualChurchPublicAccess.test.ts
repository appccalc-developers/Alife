test('public Scripture does not restore or save guest progress, even for an assigned guest ID', () => {
  const study = readFileSync(new URL('../src/views/BibleStudyView.tsx', import.meta.url), 'utf8')
  const restore = study.slice(study.indexOf('const memberId = auth.me?.id'), study.indexOf('const memberId = auth.me?.id', study.indexOf('const memberId = auth.me?.id') + 1))
  assert.match(restore, /if \(!memberId \|\| auth.isGuest\) \{\s*setRestoredReadingMemberId\(null\)\s*return\s*\}/)
  assert.ok(restore.indexOf('if (!memberId || auth.isGuest)') < restore.indexOf('readSavedReadingPosition(memberId)'))
  assert.ok(restore.indexOf('if (!memberId || auth.isGuest)') < restore.indexOf('bibleReadingProgressService.get(request.signal)'))
  assert.match(restore, /return \(\) => \{ active = false; request.abort\(\) \}/)
  assert.match(study, /if \(!memberId \|\| auth.isGuest \|\| restoredReadingMemberId !== memberId\) return/)
  assert.match(study, /return \(\) => \{ active = false; request.abort\(\); window.clearTimeout\(syncTimer\) \}/)
  assert.match(study, /\[auth.isGuest, auth.me\?\.id, book, chapter, language, restoredReadingMemberId, searchParams\]/)
})

test('public Scripture exemption is route-scoped and leaves ordinary member Bible study guarded', () => {
  const routes = readFileSync(new URL('../src/app/routing/AppRoutes.tsx', import.meta.url), 'utf8')
  const reading = routes.split('const VirtualChurchReadingRoute =')[1].split('const EntryRoute =')[0]
  assert.match(reading, /virtualChurchGuestVisitEnabled\(\) && isVirtualChurchStudyRoomReading\(location.search\)/)
  assert.match(reading, /: <MemberRoute>\{children\}<\/MemberRoute>/)
  assert.ok(/path="\/study"\s+element=\{\s*<VirtualChurchReadingRoute>\s*<BibleStudyView \/>\s*<\/VirtualChurchReadingRoute>\s*\}/.test(routes), 'only the /study route uses the narrow guest reading guard')
  const study = readFileSync(new URL('../src/views/BibleStudyView.tsx', import.meta.url), 'utf8')
  assert.match(study, /guestFromVirtualChurch = auth.isGuest && fromVirtualChurchStudyRoom/)
  assert.match(study, /访客阅读不会保存到会员进度/)
  assert.match(study, /Guest reading is not saved to member progress/)
  assert.match(study, /backLink=\{fromVirtualChurchStudyRoom \? \{ to: '\/virtual-church\/study-room'/)
})

test('guest 3D routes skip identity and group bootstrap only while guest access is enabled', () => {
  for (const pathname of ['/virtual-church', '/virtual-church/study-room', '/virtual-church/main-hall']) {
    const location = { pathname, search: '' }
    assert.equal(isAuthOptionalLocation(location), false)
    assert.equal(isAuthOptionalLocation(location, true), true)
  }
  assert.equal(isAuthOptionalLocation({ pathname: '/study', search: '?from=virtual-church-study-room' }, true), false)
  assert.equal(isAuthOptionalLocation({ pathname: '/church', search: '' }, true), false)
})

